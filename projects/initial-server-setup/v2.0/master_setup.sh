#!/bin/bash

# ==============================================================================
# Master System Setup & Audit Script for Ansible Nodes (v4.0 - Enterprise)
# Author: Sumon (Platform Engineer)
# Features: Deep Audit, MD Report, Multi-IF Handling, Idempotent Setup
# ==============================================================================

# --- Colors & Formatting ---
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
CYAN='\033[0;36m'
BOLD='\033[1m'
UNDERLINE='\033[4m'
NC='\033[0m'

# --- Global Variables ---
OS=""
SSH_SERVICE_NAME="ssh"
REPORT_FILE="/tmp/system_audit_$(hostname)_$(date +%F).md"

# --- Helper Functions ---
log_info() { echo -e "${BLUE}[INFO]${NC} $1"; }
log_success() { echo -e "${GREEN}[SUCCESS]${NC} $1"; }
log_warn() { echo -e "${YELLOW}[WARN]${NC} $1"; }
log_error() { echo -e "${RED}[ERROR]${NC} $1"; }

get_input() {
    local prompt="$1"
    local default_val="$2"
    local input_var_name="$3"
    if [ -n "$default_val" ]; then
        read -p "${prompt} [${CYAN}${default_val}${NC}]: " input_val
        eval "$input_var_name='${input_val:-$default_val}'"
    else
        read -p "${prompt}: " input_val
        eval "$input_var_name='$input_val'"
    fi
}

# --- Phase 1: Deep System Audit ---
generate_deep_audit() {
    log_info "Generating Deep System Audit Report (Markdown)..."
    
    # Detect System Type
    SYS_TYPE=$(dmidecode -s system-product-name 2>/dev/null || echo "Unknown")
    if [[ "$SYS_TYPE" == *"Latitude"* || "$SYS_TYPE" == *"ThinkPad"* || "$SYS_TYPE" == *"XPS"* ]]; then
        FORM_FACTOR="Laptop"
    elif [[ "$SYS_TYPE" == *"PowerEdge"* || "$SYS_TYPE" == *"ProLiant"* || "$SYS_TYPE" == *"Inspur"* ]]; then
        FORM_FACTOR="Server"
    else
        FORM_FACTOR="Desktop/VM"
    fi

    # Check Virtualization Support
    VIRT_SUPPORT="No"
    if grep -Eoc '(vmx|svm)' /proc/cpuinfo > 0; then
        VIRT_SUPPORT="Yes (VT-x/AMD-V)"
    fi

    # Check Installed Stacks
    check_stack() {
        if command -v $1 &> /dev/null; then
            echo "✅ Installed ($($1 --version 2>/dev/null | head -n1))"
        else
            echo "❌ Not Found"
        fi
    }

    # Start Writing MD Report
    cat > "$REPORT_FILE" <<EOF
# 🖥️ System Audit Report: $(hostname)
**Date:** $(date)  
**Generated By:** Master Setup Script v4.0

## 1. Hardware Specifications
| Component | Details |
| :--- | :--- |
| **Form Factor** | $FORM_FACTOR |
| **Model** | $SYS_TYPE |
| **CPU Model** | $(lscpu | grep 'Model name' | sed 's/Model name:*//' | xargs) |
| **Cores/Threads** | $(nproc) Cores |
| **Virtualization** | $VIRT_SUPPORT |
| **RAM Total** | $(free -h | grep Mem | awk '{print $2}') |
| **Swap Total** | $(free -h | grep Swap | awk '{print $2}') |
| **Disk Layout** | See Storage Section Below |

## 2. Operating System & Kernel
| Item | Value |
| :--- | :--- |
| **OS** | $(cat /etc/os-release | grep PRETTY_NAME | cut -d= -f2 | tr -d '"') |
| **Kernel** | $(uname -r) |
| **Uptime** | $(uptime -p) |

## 3. Software Stack Detection
| Technology | Status |
| :--- | :--- |
| **Docker** | $(check_stack docker) |
| **Kubernetes (kubeadm)** | $(check_stack kubeadm) |
| **K3s** | $(check_stack k3s) |
| **Nginx** | $(check_stack nginx) |
| **Apache** | $(check_stack apache2 || check_stack httpd) |
| **Python3** | $(check_stack python3) |
| **Ansible** | $(check_stack ansible) |
| **Ceph** | $(check_stack ceph) |

## 4. Network Configuration
| Interface | IP Address | Status | Type |
| :--- | :--- | :--- | :--- |
EOF

    # Loop through interfaces
    for iface in $(ls /sys/class/net/ | grep -v lo); do
        IP_ADDR=$(ip -4 addr show dev $iface 2>/dev/null | grep "inet " | awk '{print $2}' | head -n 1)
        STATE=$(ip link show $iface | grep -o "state [A-Z]*" | awk '{print $2}')
        if [ -z "$IP_ADDR" ]; then IP_ADDR="N/A"; fi
        echo "| $iface | $IP_ADDR | $STATE | - |" >> "$REPORT_FILE"
    done

    cat >> "$REPORT_FILE" <<EOF

## 5. Running Services & Background Tasks
### Active Services (Top 5 by Memory)
\`\`\`bash
$(ps aux --sort=-%mem | head -n 6)
\`\`\`

### Scheduled Cronjobs (Root & Current User)
\`\`\`bash
$(crontab -l 2>/dev/null || echo "No cronjobs found for current user")
$(sudo ls /etc/cron.d/ 2>/dev/null || echo "No system cron.d entries")
\`\`\`

## 6. Security & SSH Status
| Setting | Value |
| :--- | :--- |
| **SSH Service** | $(systemctl is-active $SSH_SERVICE_NAME) |
| **Root Login** | $(grep '^PermitRootLogin' /etc/ssh/sshd_config 2>/dev/null | awk '{print $2}') |
| **Password Auth** | $(grep '^PasswordAuthentication' /etc/ssh/sshd_config 2>/dev/null | awk '{print $2}') |

---
*Report generated automatically.*
EOF

    log_success "Audit Report saved at: $REPORT_FILE"
    echo -e "${CYAN}--- Previewing Audit Report ---${NC}"
    cat "$REPORT_FILE"
}

# --- Phase 2: Smart Network & Input ---
collect_inputs() {
    echo -e "\n${BLUE}======================================================${NC}"
    echo -e "${BOLD}  CONFIGURATION SETUP (Press Enter for Default)       ${NC}"
    echo -e "${BLUE}======================================================${NC}"

    get_input "Enter New Hostname" "$(hostname)" NEW_HOSTNAME
    
    # Detect Primary Interface (The one with Default Gateway)
    PRIMARY_IF=$(ip route | grep default | head -n 1 | awk '{print $5}')
    CURRENT_IP=$(ip -4 addr show dev $PRIMARY_IF 2>/dev/null | grep "inet " | awk '{print $2}' | cut -d/ -f1)
    CURRENT_GW=$(ip route | grep default | head -n 1 | awk '{print $3}')

    echo -e "${YELLOW}Detected Primary Interface: ${CYAN}$PRIMARY_IF${NC} (${CURRENT_IP})"
    
    read -p "Configure Static IP for $PRIMARY_IF? (yes/no) [${CYAN}yes${NC}]: " SET_STATIC
    SET_STATIC=${SET_STATIC:-yes}

    TARGET_IP="$CURRENT_IP"
    TARGET_GW="$CURRENT_GW"
    TARGET_DNS="8.8.8.8"

    if [[ "$SET_STATIC" =~ ^[Yy] ]]; then
        get_input "Static IP" "$CURRENT_IP" TARGET_IP
        get_input "Gateway" "$CURRENT_GW" TARGET_GW
        get_input "DNS" "8.8.8.8" TARGET_DNS
    fi

    get_input "Admin Username" "devops-admin" NEW_USER
    
    echo -e "\n${YELLOW}Paste Ansible Public Key (or press Enter to skip):${NC}"
    read -p "Key: " PUB_KEY
    if [ -z "$PUB_KEY" ]; then USE_KEY=false; else ANSIBLE_KEY="$PUB_KEY"; USE_KEY=true; fi
}

# --- Phase 3: Idempotent Application ---

apply_hostname() {
    if [ "$(hostname)" == "$NEW_HOSTNAME" ]; then
        log_warn "Hostname is already $NEW_HOSTNAME. Skipping."
    else
        hostnamectl set-hostname $NEW_HOSTNAME
        sed -i "s/127.0.1.1.*/127.0.1.1 $NEW_HOSTNAME/" /etc/hosts
        echo "$TARGET_IP $NEW_HOSTNAME.meghnacloud.local $NEW_HOSTNAME" >> /etc/hosts
        log_success "Hostname updated to $NEW_HOSTNAME."
    fi
}

apply_netplan() {
    if [ "$OS" == "ubuntu" ] && [[ "$SET_STATIC" =~ ^[Yy] ]]; then
        log_info "Applying Netplan for $PRIMARY_IF..."
        
        # Backup existing configs
        for f in /etc/netplan/*.yaml; do
            mv "$f" "${f}.bak" 2>/dev/null || true
        done

        cat > /etc/netplan/01-static-config.yaml <<EOF
network:
  version: 2
  renderer: networkd
  ethernets:
    $PRIMARY_IF:
      dhcp4: no
      addresses: [$TARGET_IP/24]
      routes:
        - to: default
          via: $TARGET_GW
      nameservers:
        addresses: [$TARGET_DNS, 1.1.1.1]
EOF
        chmod 600 /etc/netplan/01-static-config.yaml
        netplan apply
        log_success "Static IP applied."
    fi
}

setup_user_and_ssh() {
    # Create User if not exists
    if id -u $NEW_USER >/dev/null 2>&1; then
        log_warn "User $NEW_USER already exists. Skipping creation."
    else
        useradd -m -s /bin/bash $NEW_USER
        echo "$NEW_USER ALL=(ALL) NOPASSWD:ALL" > /etc/sudoers.d/$NEW_USER
        chmod 440 /etc/sudoers.d/$NEW_USER
        log_success "User $NEW_USER created with Sudo."
    fi

    # Set Password (Always ask for security update)
    log_info "Updating password for $NEW_USER..."
    passwd $NEW_USER

    # SSH Key
    mkdir -p /home/$NEW_USER/.ssh
    if [ "$USE_KEY" = true ]; then
        echo "$ANSIBLE_KEY" > /home/$NEW_USER/.ssh/authorized_keys
        log_success "SSH Key updated."
    fi
    chown -R $NEW_USER:$NEW_USER /home/$NEW_USER/.ssh
    chmod 700 /home/$NEW_USER/.ssh
    chmod 600 /home/$NEW_USER/.ssh/authorized_keys 2>/dev/null

    # Hardening
    sed -i 's/^PermitRootLogin.*/PermitRootLogin no/' /etc/ssh/sshd_config
    if [ "$USE_KEY" = true ]; then
        sed -i 's/^PasswordAuthentication.*/PasswordAuthentication no/' /etc/ssh/sshd_config
    else
        sed -i 's/^PasswordAuthentication.*/PasswordAuthentication yes/' /etc/ssh/sshd_config
    fi
    systemctl restart $SSH_SERVICE_NAME
    log_success "SSH Hardening applied."
}

# --- Main ---
main() {
    echo -e "${BLUE}============================================${NC}"
    echo -e "${BOLD}  MASTER SYSTEM SETUP & AUDIT (v4.0)        ${NC}"
    echo -e "${BLUE}============================================${NC}"
    
    # Detect OS
    . /etc/os-release
    OS=$ID
    [[ "$OS" == "centos" || "$OS" == "rhel" ]] && SSH_SERVICE_NAME="sshd"

    generate_deep_audit
    collect_inputs
    apply_hostname
    apply_netplan
    setup_user_and_ssh

    echo -e "\n${GREEN}============================================${NC}"
    echo -e "${GREEN}  SETUP COMPLETED!                          ${NC}"
    echo -e "${GREEN}============================================${NC}"
    echo -e "Connect via: ${CYAN}ssh $NEW_USER@$TARGET_IP${NC}"
}

main